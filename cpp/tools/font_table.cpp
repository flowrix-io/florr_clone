// Writes the client's built-in table of the bundled face's metrics.
//
//   font_table <face.ttf> <out.inc>
//
// Every run the client sets is measured, aligned, wrapped and hit-tested
// against the face's advance widths and em box (client/ui/text.cpp). Those
// numbers are fixed the moment the configure pins the font, so the build works
// them out once, here, and compiles them in (client/ui/face_metrics.h): a run
// then measures as one table read per character, with no file to load, no cmap
// to walk and nothing to ask the browser.
//
// The numbers come out of Font (third_party/cpp_canvas/font.cpp), the same
// reader the native client loads the file with at run time, so the table holds
// what that reader resolves -- not a second reading of the file that could
// disagree with it. face_metrics_tests.cpp checks the two against each other
// to the bit.
//
// Run by the build (cpp/CMakeLists.txt) on every configuration: natively on a
// native one, under the Node the emscripten toolchain found on a web one. The
// same input always gives the same bytes.

#include <cstdint>
#include <cstdio>
#include <fstream>
#include <iterator>
#include <sstream>
#include <string>
#include <vector>

#include "client/ui/face_metrics.h"
#include "font.h"

namespace {

int fail(const std::string& message) {
    std::fprintf(stderr, "font_table: %s\n", message.c_str());
    return 1;
}

std::string hex64(std::uint64_t value) {
    char buf[32];
    std::snprintf(buf, sizeof buf, "0x%016llxull", static_cast<unsigned long long>(value));
    return buf;
}

} // namespace

int main(int argc, char** argv) {
    if (argc != 3) return fail("usage: font_table <face.ttf> <out.inc>");
    const std::string input = argv[1], output = argv[2];

    std::ifstream in(input, std::ios::binary);
    if (!in) return fail("cannot read " + input);
    std::vector<std::uint8_t> bytes((std::istreambuf_iterator<char>(in)),
                                    std::istreambuf_iterator<char>());
    const std::uint64_t hash = flix::ui::face_metrics::fingerprint(bytes.data(), bytes.size());
    const std::size_t size = bytes.size();

    Font face;
    if (!face.loadFromMemory(std::move(bytes))) return fail(input + " is not a face Font can read");

    // The ASCII rows are indexed by codepoint, so the common case is one array
    // read; everything else the face maps is a sorted list to search.
    std::vector<std::uint32_t> rest;
    std::uint64_t asciiMapped[2] = {0, 0};
    for (std::uint32_t c : face.mappedCodepoints()) {
        if (c < 128) asciiMapped[c / 64] |= std::uint64_t{1} << (c % 64);
        else rest.push_back(c);
    }

    std::ostringstream out;
    out << "// Generated by cpp/tools/font_table.cpp from " << input.substr(input.find_last_of("/\\") + 1)
        << ". Do not edit:\n"
           "// the build rewrites it from the face. Read by client/ui/face_metrics.cpp.\n\n";
    out << "constexpr std::uint64_t kFileHash = " << hex64(hash) << ";\n";
    out << "constexpr std::uint64_t kFileSize = " << size << ";\n";
    out << "constexpr int kUnitsPerEm = " << face.unitsPerEm() << ";\n";
    out << "constexpr int kEmAscent = " << face.emAscent() << ";\n";
    out << "constexpr int kEmDescent = " << face.emDescent() << ";\n";
    // A codepoint no face maps, for .notdef's advance.
    out << "constexpr std::uint16_t kNotdef = " << face.metrics(0xFFFFFFFFu).advance << ";\n";
    out << "constexpr std::uint64_t kAsciiMapped[2] = {" << hex64(asciiMapped[0]) << ", "
        << hex64(asciiMapped[1]) << "};\n";
    out << "constexpr std::uint16_t kAscii[128] = {";
    for (std::uint32_t c = 0; c < 128; ++c) {
        out << (c % 16 ? " " : "\n    ") << face.metrics(c).advance << ',';
    }
    out << "\n};\n";
    out << "constexpr std::size_t kMappedCount = " << rest.size() << ";\n";
    out << "constexpr std::uint32_t kMapped[kMappedCount] = {";
    for (std::size_t i = 0; i < rest.size(); ++i) out << (i % 12 ? " " : "\n    ") << rest[i] << ',';
    out << "\n};\n";
    out << "constexpr std::uint16_t kMappedAdvance[kMappedCount] = {";
    for (std::size_t i = 0; i < rest.size(); ++i) {
        out << (i % 16 ? " " : "\n    ") << face.metrics(rest[i]).advance << ',';
    }
    out << "\n};\n";

    std::ofstream file(output, std::ios::binary | std::ios::trunc);
    if (!file) return fail("cannot write " + output);
    file << out.str();
    if (!file.flush()) return fail("cannot write " + output);
    return 0;
}
